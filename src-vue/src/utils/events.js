// 生成 ALL_EVENTS（从 CHAPTERS 展开）
export function buildAllEvents(customEvents = []) {
  const all = []
  CHAPTERS.forEach((ch, ci) => {
    ch.events.forEach((ev, ei) => {
      all.push({ id: ci + '-' + ei, chapter: ci, name: ev })
    })
  })
  // 追加自定义事件
  customEvents.forEach(ce => {
    all.push({ id: ce.id, chapter: ce.chapterIndex, name: ce.name, custom: true })
  })
  return all
}
